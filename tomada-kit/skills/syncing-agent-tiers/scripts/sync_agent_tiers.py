#!/usr/bin/env python3
"""Render the canonical sub-agent tiers into repositories and open one PR per repo.

Usage:
  sync_agent_tiers.py --render <repo-dir>     write the tier files into a checkout, no git
  sync_agent_tiers.py --dry-run [repo ...]    show which repos would change
  sync_agent_tiers.py [repo ...]              branch, commit, push, open a PR, queue auto-merge

Repos default to assets/repos.json. Each repo is worked on in a temporary git worktree
cut from origin/main, so the local checkout's branch and changes are never touched.
Standard library only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parents[1]
TIERS = json.loads((SKILL_DIR / "assets" / "tiers.json").read_text("utf-8"))["tiers"]
REPOS = json.loads((SKILL_DIR / "assets" / "repos.json").read_text("utf-8"))
GHQ_ROOT = Path.home() / "ghq" / "github.com"
BRANCH = "chore/sync-agent-tiers-" + hashlib.sha1(
    (SKILL_DIR / "assets" / "tiers.json").read_bytes()).hexdigest()[:8]
TITLE = "chore(agents): sync sub-agent tiers"
BODY = (
    "Generated by the `syncing-agent-tiers` skill: `.claude/agents/` (and `.codex/agents/` "
    "where present) now match the canonical tier definitions. Only tier files change, so "
    "auto-merge is queued for when the required checks pass."
)


def claude_text(t: dict) -> str:
    desc = textwrap.fill(t["description"], width=88, initial_indent="  ", subsequent_indent="  ")
    lines = ["---", f"name: {t['name']}", "description: >", desc,
             f"model: {t['model']}", f"effort: {t['effort']}"]
    lines += [f"{k}: {v}" for k, v in t.get("extra_frontmatter", {}).items()]
    return "\n".join(lines) + "\n---\n\n" + t["body"]


def codex_text(t: dict) -> str:
    desc = t["codex_description"].replace('"', '\\"')
    return (
        f"# The {t['name']} tier; .claude/agents/{t['name']}.md is its Claude Code twin. "
        "Generated by\n# syncing-agent-tiers: edit the canonical tiers.json, not this file. "
        "`model` is omitted\n# so the session's model is inherited.\n"
        f'name = "{t["name"]}"\ndescription = "{desc}"\n'
        f'model_reasoning_effort = "{t["codex_effort"]}"\n'
        f'developer_instructions = """\n{t["body"]}"""\n'
    )


def render(repo_dir: Path) -> list[str]:
    """Write tier files; return the paths written, relative to repo_dir."""
    written = []
    claude_dir = repo_dir / ".claude" / "agents"
    claude_dir.mkdir(parents=True, exist_ok=True)
    codex_dir = repo_dir / ".codex" / "agents"
    for t in TIERS:
        (claude_dir / f"{t['name']}.md").write_text(claude_text(t), "utf-8")
        written.append(f".claude/agents/{t['name']}.md")
        if codex_dir.is_dir():
            (codex_dir / f"{t['name']}.toml").write_text(codex_text(t), "utf-8")
            written.append(f".codex/agents/{t['name']}.toml")
    return written


def run(cmd: list[str], cwd: Path, check: bool = True) -> str:
    res = subprocess.run(cmd, cwd=cwd, text=True, capture_output=True)
    if check and res.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} failed in {cwd}:\n{res.stderr.strip()}")
    return res.stdout.strip()


def local_clone(repo: str) -> Path:
    path = GHQ_ROOT / REPOS["owner"] / repo
    if not path.is_dir():
        run(["gh", "repo", "clone", f"{REPOS['owner']}/{repo}", str(path)], cwd=Path.home())
    return path


def sync_repo(repo: str, dry_run: bool) -> str:
    clone = local_clone(repo)
    run(["git", "fetch", "origin", "main"], cwd=clone)
    tmp = Path(tempfile.mkdtemp(prefix=f"agent-tiers-{repo}-"))
    shutil.rmtree(tmp)
    run(["git", "worktree", "add", "--detach", str(tmp), "origin/main"], cwd=clone)
    try:
        render(tmp)
        changed = run(["git", "status", "--porcelain"], cwd=tmp)
        if not changed:
            return "up to date"
        if dry_run:
            return "would change:\n    " + changed.replace("\n", "\n    ")
        run(["git", "switch", "-C", BRANCH], cwd=tmp)
        run(["git", "add", ".claude/agents", *([".codex/agents"] if (tmp / ".codex/agents").is_dir() else [])], cwd=tmp)
        run(["git", "commit", "-m", TITLE], cwd=tmp)
        if not run(["git", "ls-remote", "--heads", "origin", BRANCH], cwd=tmp):
            run(["git", "push", "-u", "origin", BRANCH], cwd=tmp)
        existing = run(["gh", "pr", "list", "--head", BRANCH, "--json", "url", "-q", ".[0].url"], cwd=tmp)
        url = existing or run(["gh", "pr", "create", "--base", "main", "--head", BRANCH,
                               "--title", TITLE, "--body", BODY], cwd=tmp)
        info = json.loads(run(["gh", "api", f"repos/{REPOS['owner']}/{repo}"], cwd=tmp))
        method = next((m for m, k in (("--squash", "allow_squash_merge"), ("--rebase", "allow_rebase_merge"),
                                       ("--merge", "allow_merge_commit")) if info.get(k)), "--merge")
        if not info.get("allow_auto_merge"):
            return f"PR opened (auto-merge is disabled in repo settings — merge it yourself): {url}"
        run(["gh", "pr", "merge", url, "--auto", method], cwd=tmp)
        return f"PR opened, auto-merge queued: {url}"
    finally:
        run(["git", "worktree", "remove", "--force", str(tmp)], cwd=clone, check=False)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("repos", nargs="*", help="repo names (default: assets/repos.json)")
    ap.add_argument("--render", type=Path, help="write tier files into this checkout and exit")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    if args.render:
        for p in render(args.render.resolve()):
            print(p)
        return 0
    failed = 0
    for repo in args.repos or REPOS["repos"]:
        try:
            print(f"{repo}: {sync_repo(repo, args.dry_run)}")
        except Exception as e:  # report every repo, fail at the end
            failed += 1
            print(f"{repo}: FAILED — {e}", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
